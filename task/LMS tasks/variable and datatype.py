# Create variables of different types: integer, float, string, list, tuple, dictionary, set, frozenset, boolean, and NoneType.
# Print each variable along with its type using the type() function.
# integer
num_int = 10
print("integer:", num_int, "type:", type(num_int))
# float
num_float = 12.34
print("float:", num_float, "type:", type(num_float))
# string
num_str = "building"
print("string:", num_str, "type:", type(num_str))
# list
list1 = [23, 45, "boat", "car", 34.56]
print("list:", list1, "type:", type(list1))
# tuple
tuple1 = (34, 30, 32, "banana", 35.5)
print("tuple:", tuple1, "type:", type(tuple1))
# dictionary
dict1 = {"name": "nisam", "age": 22}
print("dictionary:", dict1, "type:", type(dict1))
# set
set1 = {1, 2, 3, "baby"}
print("set:", set1, "type:", type(set1))
# frozen set
frozenset1 = frozenset([1, 2, 3, 4, 5])
print("Frozenset:", frozenset1, "Type:", type(frozenset1))
# boolean
boolean = True
print("boolean:", boolean, "type:", type(boolean))
# nonetype
nothing = None
print("NoneType:", nothing, "Type:", type(nothing))
